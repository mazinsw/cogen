// Generates src/generated/vocabulary.ts from the template grammar and README,
// so completion and hover never drift from the parser.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(root, '..');
const lexer = readFileSync(join(repo, 'src/grammar/TemplateLexer.g4'), 'utf8');
const parser = readFileSync(
  join(repo, 'src/grammar/TemplateParser.g4'),
  'utf8',
);
const readme = readFileSync(join(repo, 'README.md'), 'utf8');

// K_FEW_FIELDS: F E W '_' F I E L D S;  ->  few_fields
const keywords = {};
for (const [, name, body] of lexer.matchAll(/^(K_\w+):\s*([^;]+);/gm)) {
  keywords[name] = body
    .trim()
    .split(/\s+/)
    .map((part) => part.replace(/'/g, '').toLowerCase())
    .join('');
}

function ruleTokens(rule) {
  const match = parser.match(new RegExp(`^${rule}:([^;]+);`, 'm'));
  if (!match) throw new Error(`Rule ${rule} not found`);
  return [...match[1].matchAll(/K_\w+/g)].map(([token]) => keywords[token]);
}

// control words available for each block level, from rules like
// fieldIfStmt: OPEN K_FIELD DOT+ NOT? K_IF ...
const controlTokens = {
  K_IF: 'if',
  K_EXISTS: 'exists',
  K_CONTAINS: 'contains',
  K_EACH: 'each',
  K_REVERSE_EACH: 'reverse_each',
  FINDS_OPEN: 'finds',
  MATCH_OPEN: 'match',
};
const controls = {};
for (const [, level, control] of parser.matchAll(
  /^\w+Stmt:\s*OPEN (K_\w+) DOT\+ (?:NOT\? )?(K_IF|K_EXISTS|K_CONTAINS|K_EACH|K_REVERSE_EACH|FINDS_OPEN|MATCH_OPEN)\b/gm,
)) {
  const list = (controls[keywords[level]] ??= []);
  if (!list.includes(controlTokens[control])) list.push(controlTokens[control]);
}

// README: "- `$[table.unix]` Table name in unix format"
//         "    - generated: virtual or stored generated column"
function docKey(command) {
  return command
    .toLowerCase()
    .replace(/\([^)]*\)?\)?/g, '')
    .replace(/~/g, '')
    .replace(/\.+$/, '');
}
const docs = {};
function addDoc(key, text) {
  if (!key || !text) return;
  docs[key] =
    docs[key] && !docs[key].includes(text) ? `${docs[key]}\n\n${text}` : text;
}
let lastKey = null;
let inAttributes = false;
for (const line of readme.split('\n')) {
  const command = line.match(/^\s*- `\$\[(.+?)\]`(.*)$/);
  if (command) {
    let rest = command[2].trim();
    const keys = [docKey(command[1])];
    const alias = rest.match(/^or `\$\[(.+?)\]`(.*)$/);
    if (alias) {
      keys.push(docKey(alias[1]));
      rest = alias[2].trim();
    }
    const text = `\`$[${command[1]}]\`${rest ? ' — ' + rest : ''}`;
    keys.forEach((key) => addDoc(key, text));
    lastKey = keys[0];
    inAttributes = /attributes:?\s*$/.test(rest) || /if\(/.test(command[1]);
    continue;
  }
  const example = line.match(/^\s+(?:- )?((?:legacy )?example: .+)$/);
  if (example && lastKey) {
    addDoc(lastKey, example[1]);
    continue;
  }
  const attribute = line.match(/^\s{4}- (\w+)(?::\s*(.+))?$/);
  if (attribute && inAttributes) {
    addDoc(`attr:${attribute[1].toLowerCase()}`, attribute[2] || '');
    continue;
  }
  if (/^\S/.test(line) || /^## /.test(line)) {
    inAttributes = false;
  }
}

const vocabulary = {
  tableLevels: ruleTokens('tableLevel'),
  fieldLevels: ruleTokens('fieldLevel'),
  constraintLevels: ruleTokens('constraintLevel'),
  tableProps: ruleTokens('tableProp'),
  fieldProps: ruleTokens('fieldProp'),
  attributes: ruleTokens('attribute'),
  properties: ruleTokens('property'),
  types: ruleTokens('type'),
  controls,
};

writeFileSync(
  join(root, 'src/generated/vocabulary.ts'),
  '// Generated by scripts/gen-vocabulary.mjs from TemplateLexer.g4, TemplateParser.g4\n' +
    '// and README.md, do not edit\n' +
    `export const VOCABULARY = ${JSON.stringify(vocabulary, null, 2)};\n\n` +
    `export const DOCS: Record<string, string> = ${JSON.stringify(docs, null, 2)};\n`,
);
console.log(
  `Generated vocabulary: ${Object.keys(controls).length} block levels, ${Object.keys(docs).length} docs`,
);
