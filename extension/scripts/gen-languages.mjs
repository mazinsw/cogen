// Generates one cogen language per host language listed in languages.json:
// grammar, language configuration and the package.json contributions.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const hosts = JSON.parse(readFileSync(join(root, 'languages.json'), 'utf8'));

const PLAIN = {
  id: 'plain',
  name: 'Plain',
  hostLanguage: 'plaintext',
  extensions: [],
  scope: null,
  comments: {},
};

const FOLDING_MARKERS = {
  start:
    '\\$\\[\\w+\\.+~?(?:if|exists|contains|match|finds|each|reverse_each)\\b',
  end: '\\$\\[\\w+\\.end\\]',
};

function languageId(host) {
  return `cogen-${host.id}`;
}

function languageConfiguration(host) {
  const pairs = [
    ['{', '}'],
    ['[', ']'],
    ['(', ')'],
  ];
  const quotes = [
    { open: '"', close: '"', notIn: ['string'] },
    { open: "'", close: "'", notIn: ['string', 'comment'] },
  ];
  return {
    comments: host.comments,
    brackets: pairs,
    autoClosingPairs: [
      ...pairs.map(([open, close]) => ({ open, close })),
      ...quotes,
    ],
    surroundingPairs: [...pairs, ['"', '"'], ["'", "'"], ['`', '`']],
    folding: { markers: FOLDING_MARKERS },
  };
}

function grammar(host) {
  return {
    $schema:
      'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
    name: `Cogen (${host.name})`,
    scopeName: `source.cogen.${host.id}`,
    patterns: [{ include: host.scope }],
  };
}

function write(file, data) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
}

rmSync(join(root, 'syntaxes/generated'), { recursive: true, force: true });
rmSync(join(root, 'language-configuration'), { recursive: true, force: true });

const all = [...hosts, PLAIN];
const icon = { light: './images/cogen.svg', dark: './images/cogen.svg' };
const languages = [];
const grammars = [];
for (const host of all) {
  const id = languageId(host);
  const configPath = `./language-configuration/${id}.json`;
  write(join(root, configPath), languageConfiguration(host));
  languages.push({
    id,
    aliases: [`Cogen (${host.name})`],
    // VS Code picks the longest matching extension, so `.ts.cgn` wins over `.cgn`
    extensions:
      host === PLAIN ? ['.cgn'] : host.extensions.map((ext) => `.${ext}.cgn`),
    configuration: configPath,
    icon,
  });
  if (host === PLAIN) {
    grammars.push({
      language: id,
      scopeName: 'source.cogen.plain',
      path: './syntaxes/cogen-plain.tmLanguage.json',
    });
    continue;
  }
  const grammarPath = `./syntaxes/generated/${id}.tmLanguage.json`;
  write(join(root, grammarPath), grammar(host));
  grammars.push({
    language: id,
    scopeName: `source.cogen.${host.id}`,
    path: grammarPath,
    ...(host.embeddedLanguages
      ? { embeddedLanguages: host.embeddedLanguages }
      : {}),
  });
}
grammars.push({
  scopeName: 'cogen.injection',
  path: './syntaxes/cogen.injection.tmLanguage.json',
  injectTo: grammars.map((item) => item.scopeName),
});

const packagePath = join(root, 'package.json');
const pkg = JSON.parse(readFileSync(packagePath, 'utf8'));
const languageIds = languages.map((item) => item.id);
pkg.activationEvents = [
  'onStartupFinished',
  ...languageIds.map((id) => `onLanguage:${id}`),
];
pkg.contributes = {
  ...pkg.contributes,
  languages,
  grammars,
  snippets: languageIds.map((language) => ({
    language,
    path: './snippets/cogen.json',
  })),
};
writeFileSync(packagePath, JSON.stringify(pkg, null, 2) + '\n');

const runtime = all.map((host) => ({
  id: languageId(host),
  hostLanguage: host.hostLanguage,
  extensions: host.extensions,
}));
writeFileSync(
  join(root, 'src/generated/languages.ts'),
  '// Generated by scripts/gen-languages.mjs, do not edit\n' +
    'export interface CogenLanguage {\n' +
    '  id: string;\n' +
    '  hostLanguage: string;\n' +
    '  extensions: string[];\n' +
    '}\n\n' +
    `export const PLAIN_LANGUAGE_ID = '${languageId(PLAIN)}';\n\n` +
    `export const LANGUAGES: CogenLanguage[] = ${JSON.stringify(runtime, null, 2)};\n`,
);
console.log(`Generated ${languages.length} cogen languages`);
